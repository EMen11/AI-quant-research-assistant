class StrictModel(BaseModel):
    """Base contract: immutable, strict and closed to unknown fields."""

    model_config = ConfigDict(extra="forbid", frozen=True, strict=True)


class MetricRecord(StrictModel):
    """Authoritative numeric record created only by Python from QuantAnalysis."""

    metric_id: Identifier
    run_id: Identifier
    metric_name: Identifier
    value: float
    unit: NonEmptyText
    horizon_or_frequency: NonEmptyText
    formula_version: NonEmptyText
    snapshot_id: Identifier

    @field_validator("value")
    @classmethod
    def finite_value(cls, value: float) -> float:
        if not math.isfinite(value):
            raise ValueError("MetricRecord value must be finite.")
        return value


class EvidenceRecord(StrictModel):
    """Server-owned synthetic or official evidence; never generated by an LLM."""

    evidence_id: Identifier
    run_id: Identifier
    document_id: Identifier
    document_sha256: Sha256
    page: int = Field(ge=1)
    excerpt: Annotated[str, Field(min_length=1, max_length=4_000)]
    period: NonEmptyText
    unit: str | None = Field(default=None, min_length=1, max_length=80)
    status: Literal["synthetic_demo_evidence", "official_corpus_passage"]
    passage_id: Identifier | None = None
    source_record_type: str | None = Field(default=None, min_length=1, max_length=80)
    source_record_id: Identifier | None = None
    issuer_id: Identifier | None = None
    publication_date: date | None = None
    printed_page: int | None = Field(default=None, ge=1)

    @model_validator(mode="after")
    def provenance_matches_status(self) -> EvidenceRecord:
        official_fields = (
            self.passage_id,
            self.source_record_type,
            self.source_record_id,
            self.issuer_id,
            self.publication_date,
        )
        if self.status == "official_corpus_passage" and any(
            value is None for value in official_fields
        ):
            raise ValueError("Official corpus evidence requires complete source provenance.")
        if self.status == "synthetic_demo_evidence" and any(
            value is not None for value in (*official_fields, self.printed_page)
        ):
            raise ValueError("Synthetic evidence cannot claim official source provenance.")
        return self


class GenerationParameter(StrictModel):
    """One provider-neutral generation parameter recorded for audit."""

    name: Identifier
    value: str | int | float | bool


class GenerationMetadata(StrictModel):
    """Provider-neutral generation parameters and optional per-attempt call metadata."""

    provider: Identifier
    model_id: Identifier
    parameters: tuple[GenerationParameter, ...]
    prompt_version: Identifier
    response_id: Annotated[str, Field(min_length=1, max_length=200)]
    generated_at: datetime
    model_call: ModelCallMetadata | None = None

    @field_validator("generated_at")
    @classmethod
    def generated_at_is_utc(cls, value: datetime) -> datetime:
        _require_utc(value, "generated_at")
        return value


class ClaimProposal(StrictModel):
    """Untrusted structured content proposed by the fake, without a claim ID."""

    text_template: Annotated[str, Field(min_length=1, max_length=1_000)]
    claim_type: ClaimType
    metric_ids: tuple[Identifier, ...] = ()
    evidence_ids: tuple[Identifier, ...] = ()
    uncertainty: str | None = Field(default=None, max_length=500)

    @model_validator(mode="after")
    def validate_reference_shape(self) -> ClaimProposal:
        if len(set(self.metric_ids)) != len(self.metric_ids):
            raise ValueError("metric_ids must be unique within a claim.")
        if len(set(self.evidence_ids)) != len(self.evidence_ids):
            raise ValueError("evidence_ids must be unique within a claim.")
        if self.claim_type == "quantitative" and not self.metric_ids:
            raise ValueError("A quantitative claim must reference at least one metric_id.")
        if self.claim_type == "evidence" and not self.evidence_ids:
            raise ValueError("An evidence claim must reference at least one evidence_id.")
        return self


class DraftProposal(StrictModel):
    """Exact structured-output schema accepted from the fake generator."""

    summary: NonEmptyText
    claims: Annotated[tuple[ClaimProposal, ...], Field(min_length=1, max_length=12)]
    limitations: Annotated[tuple[NonEmptyText, ...], Field(min_length=1, max_length=12)]


PublicFixtureLimitation = Literal[
    "editorial-redundancy-in-evidence-claim",
    "null-uncertainty-on-two-evidence-claims",
]


class PublicFixturePromotionReview(StrictModel):
    """Explicit human promotion decision, separate from a run-level HumanReview."""

    disposition: Literal["approved"] = "approved"
    review_basis: Literal["explicit-user-approval"] = "explicit-user-approval"
    reviewed_on: date
    accepted_non_blocking_limitations: tuple[PublicFixtureLimitation, ...]

    @model_validator(mode="after")
    def limitations_are_exact(self) -> PublicFixturePromotionReview:
        expected: tuple[PublicFixtureLimitation, ...] = (
            "editorial-redundancy-in-evidence-claim",
            "null-uncertainty-on-two-evidence-claims",
        )
        if self.accepted_non_blocking_limitations != expected:
            raise ValueError("Public fixture promotion must record both accepted limitations.")
        return self


class PublicDemoFixture(StrictModel):
    """Human-approved public fixture derived from a normalized live response."""

    schema_version: Literal["public-demo-fixture.v1"] = "public-demo-fixture.v1"
    status: Literal["approved_for_public_demo"] = "approved_for_public_demo"
    demo_eligible: Literal[True] = True
    promotion_policy: Literal["explicit_human_approval_recorded"] = (
        "explicit_human_approval_recorded"
    )
    fixture_derivation: Literal["live_derived_deterministically_normalized"] = (
        "live_derived_deterministically_normalized"
    )
    normalization_version: Literal["canonical-summary-v1"] = "canonical-summary-v1"
    normalized_fields: tuple[Literal["summary"], ...] = ("summary",)
    raw_provider_response_persisted: Literal[False] = False
    source_artifact_type: Literal["rejected_live_capture"] = "rejected_live_capture"
    source_artifact_sha256: Sha256
    source_candidate_schema_version: Literal["sanitized-live-capture-candidate.v1"]
    source_candidate_sha256: Sha256
    validated_input_schema_version: Literal["validated-run-input.v1"]
    validation_status: Literal["validated"] = "validated"
    render_status: Literal["reliable"] = "reliable"
    run_id: Identifier
    provider: Identifier
    model_id: NonEmptyText
    prompt_version: Literal["trust-synthesis-v3"]
    allowed_metric_ids: Annotated[tuple[Identifier, ...], Field(min_length=1)]
    evidence: Annotated[tuple[EvidenceRecord, ...], Field(min_length=1)]
    proposal: DraftProposal
    model_call: ModelCallMetadata
    promotion_review: PublicFixturePromotionReview

    @model_validator(mode="after")
    def provenance_and_allowlists_are_consistent(self) -> PublicDemoFixture:
        canonical_summary = (
            "This report presents historical run metrics and a separate official evidence "
            "record. Each is reported independently, and no temporal, causal, predictive or "
            "investment relationship between them is asserted."
        )
        if self.proposal.summary != canonical_summary:
            raise ValueError("Public fixture summary must be canonical-summary-v1.")
        if self.normalized_fields != ("summary",):
            raise ValueError("Public fixture may normalize only the summary.")
        if any(record.run_id != self.run_id for record in self.evidence):
            raise ValueError("Every public fixture evidence record must belong to its run.")
        if any(record.status != "official_corpus_passage" for record in self.evidence):
            raise ValueError("Public fixture evidence must come from the official corpus.")
        metric_ids = {
            metric_id for claim in self.proposal.claims for metric_id in claim.metric_ids
        }
        evidence_ids = {
            evidence_id for claim in self.proposal.claims for evidence_id in claim.evidence_ids
        }
        if metric_ids != set(self.allowed_metric_ids):
            raise ValueError("Public fixture metric references must match its allowlist.")
        if evidence_ids != {record.evidence_id for record in self.evidence}:
            raise ValueError("Public fixture evidence references must match its records.")
        evidence_claims = tuple(
            claim for claim in self.proposal.claims if claim.claim_type == "evidence"
        )
        if sum(claim.uncertainty is None for claim in evidence_claims) != 2:
            raise ValueError("Public fixture must retain the two accepted null uncertainties.")
        if sum(
            "reports a zero value explicitly reported" in claim.text_template
            for claim in evidence_claims
        ) != 1:
            raise ValueError("Public fixture must retain the accepted editorial redundancy.")
        if len(set(self.allowed_metric_ids)) != len(self.allowed_metric_ids):
            raise ValueError("Public fixture metric allowlist must be unique.")
        if (
            self.model_call.provider != self.provider
            or self.model_call.model_id != self.model_id
            or self.model_call.prompt_version != self.prompt_version
        ):
            raise ValueError("Public fixture identity must match its live call metadata.")
        if self.model_call.response_origin != "live_provider":
            raise ValueError("Public fixture must retain its live provider origin.")
        if self.model_call.status != "schema_error":
            raise ValueError("Public fixture must retain the historical source call status.")
        if self.model_call.response_id is None or self.model_call.provider_request_id is None:
            raise ValueError("Public fixture requires source request and response IDs.")
        return self


