class RenderedClaim(StrictModel):
    """Claim text after Python has injected trusted numeric values."""

    run_id: Identifier
    claim_id: Identifier
    text: NonEmptyText
    metric_references: tuple[ClaimMetricReference, ...]
    evidence_references: tuple[ClaimEvidenceReference, ...]

    @model_validator(mode="after")
    def references_belong_to_claim(self) -> RenderedClaim:
        references = (*self.metric_references, *self.evidence_references)
        if any(reference.run_id != self.run_id for reference in references):
            raise ValueError("Every rendered reference must belong to the rendered run.")
        if any(reference.claim_id != self.claim_id for reference in references):
            raise ValueError("Every rendered reference must belong to the rendered claim.")
        return self


class RenderedDraft(StrictModel):
    """Reliable rendering exists only when deterministic validation succeeds."""

    run_id: Identifier
    draft_id: Identifier
    reliable: bool
    final_text: str | None = None
    claims: tuple[RenderedClaim, ...] = ()

    @model_validator(mode="after")
    def final_text_matches_reliability(self) -> RenderedDraft:
        if self.reliable and (not self.final_text or not self.claims):
            raise ValueError("Reliable rendering requires final text and claims.")
        if not self.reliable and (self.final_text is not None or self.claims):
            raise ValueError("Blocked rendering cannot emit final text or claims.")
        if any(claim.run_id != self.run_id for claim in self.claims):
            raise ValueError("Every rendered claim must belong to the rendered run.")
        return self


class AutomatedAssessment(StrictModel):
    """Automatic routing status; never an approval or human disposition."""

    run_id: Identifier
    status: AssessmentStatus
    reason_codes: Annotated[tuple[AssessmentReason, ...], Field(min_length=1)]

    @model_validator(mode="after")
    def reason_matches_status(self) -> AutomatedAssessment:
        expected: dict[AssessmentStatus, AssessmentReason] = {
            "eligible_for_review": "validated_references",
            "review_required": "blocking_validation_issues",
            "abstain": "insufficient_trusted_inputs",
        }
        if self.reason_codes != (expected[self.status],):
            raise ValueError("Assessment reason_codes must match status exactly.")
        return self


class HumanReview(StrictModel):
    """Decision created only by an explicit human action."""

    run_id: Identifier
    reviewer_id: Identifier
    comment: NonEmptyText
    reviewed_at: datetime
    disposition: HumanDisposition

    @field_validator("reviewed_at")
    @classmethod
    def reviewed_at_is_utc(cls, value: datetime) -> datetime:
        _require_utc(value, "reviewed_at")
        return value


def _require_utc(value: datetime, field_name: str) -> None:
    if value.tzinfo is None or value.utcoffset() != timedelta(0):
        raise ValueError(f"{field_name} must be timezone-aware UTC.")
