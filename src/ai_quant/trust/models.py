class ValidationReport(StrictModel):
    """Trusted validation result, distinct from generation and assessment."""

    run_id: Identifier
    draft_id: Identifier
    issues: tuple[ValidationIssue, ...]
    trusted_input_count: int = Field(ge=0)
    identifier_checks_passed: bool
    value_checks_passed: bool
    run_membership_checks_passed: bool

    @property
    def has_blocking_issues(self) -> bool:
        """Return whether any issue prevents reliable rendering."""

        return any(issue.severity in {"error", "critical"} for issue in self.issues)

    @model_validator(mode="after")
    def check_summary_flags(self) -> ValidationReport:
        expected_identifier = not any(
            issue.code in IDENTIFIER_FAILURE_CODES for issue in self.issues
        )
        expected_value = not any(
            issue.code in VALUE_FAILURE_CODES
            for issue in self.issues
        )
        expected_membership = not any(
            issue.code == "cross_run_reference" for issue in self.issues
        )
        if self.identifier_checks_passed != expected_identifier:
            raise ValueError("identifier_checks_passed contradicts the issue list.")
        if self.value_checks_passed != expected_value:
            raise ValueError("value_checks_passed contradicts the issue list.")
        if self.run_membership_checks_passed != expected_membership:
            raise ValueError("run_membership_checks_passed contradicts the issue list.")
        return self


